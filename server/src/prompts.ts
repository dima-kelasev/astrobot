  'Не строй фразы по схемам «не X, а Y» и «не просто X, но и Y». Не задавай риторических вопросов. Не ставь подряд три однородных слова ради ритма.',
  'Чередуй короткие предложения с длинными. Не начинай соседние предложения с одного слова и не повторяй «вы», «вам», «ваш» в каждой фразе.',
  'Пиши без тире и восклицательных знаков. Если просится тире, перестрой предложение.',
